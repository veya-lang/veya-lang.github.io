#!/usr/bin/env python3
"""Builds the site: index.html from index.src.html (with samples/*.veya
highlighted) and guide.html from sections of the compiler's README.

    python3 -m venv .venv && .venv/bin/pip install markdown pygments
    .venv/bin/python tools/build.py ../veya/README.md
"""
import html
import re
import sys
from pathlib import Path

import markdown
from pygments import highlight
from pygments.formatters import HtmlFormatter
from pygments.lexers import RubyLexer

ROOT = Path(__file__).resolve().parent.parent

# README sections (## headings, with their ### parts) that make up the
# guide, in order
GUIDE = [
    "The language in one page",
    "Quick start",
    "Testing",
    "Projects and packages",
    "Macros",
    "Example apps",
    "Performance",
    "How it works",
]

FMT = HtmlFormatter(cssclass="hl", nowrap=False)


def code(src: str) -> str:
    return highlight(src.rstrip("\n") + "\n", RubyLexer(), FMT)


def code_css() -> str:
    light = HtmlFormatter(style="friendly").get_style_defs(".hl")
    dark = HtmlFormatter(style="monokai").get_style_defs(".hl")
    # the boxes come from style.css
    strip = lambda css: re.sub(r"\.hl \{[^}]*\}", "", re.sub(r"^.*(\.linenos|pre \{|td\.|span\.linenos).*$", "", css, flags=re.M))
    strip_err = lambda css: re.sub(r"^.*\.err .*$", "", css, flags=re.M)
    light, dark = strip_err(light), strip_err(dark)
    return "/* generated by tools/build.py */\n" + strip(light) + "\n@media (prefers-color-scheme: dark) {\n" + strip(dark) + "\n}\n.hl pre { background: var(--code-bg); }\n"


def build_index():
    src = (ROOT / "index.src.html").read_text()
    out = re.sub(r"\{\{code:(\w+)\}\}", lambda m: code((ROOT / "samples" / f"{m.group(1)}.veya").read_text()), src)
    (ROOT / "index.html").write_text(out)


def sections(readme: str) -> dict:
    """heading → its markdown (with its subsections), for ## and ### headings"""
    found = {}
    lines = readme.split("\n")
    heads = [(i, len(m.group(1)), m.group(2).strip()) for i, l in enumerate(lines) if (m := re.match(r"^(#{2,3}) (.+)$", l))]
    for k, (i, level, title) in enumerate(heads):
        end = next((j for j, lv, _ in heads[k + 1:] if lv <= level), len(lines))
        found[title] = (level, "\n".join(lines[i + 1:end]))
    return found


def slug(t: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", t.lower()).strip("-")


def build_guide(readme_path: str):
    readme = Path(readme_path).read_text()
    secs = sections(readme)
    md_parts = []
    toc = []
    for title in GUIDE:
        _, body = secs[title]
        md_parts.append(f"## {title}\n\n{body}")
    md = "\n\n".join(md_parts)
    # links to files in the repository go to GitHub
    md = re.sub(r"\]\((?!https?:|#)([^)]+)\)", r"](https://github.com/veya-lang/veya/blob/main/\1)", md)
    conv = markdown.Markdown(extensions=["fenced_code", "tables", "toc", "codehilite"], extension_configs={"codehilite": {"css_class": "hl", "guess_lang": False}, "toc": {"slugify": lambda v, sep: slug(v)}})
    body = conv.convert(md)
    for tok in conv.toc_tokens:
        toc.append(f'<a href="#{tok["id"]}">{html.escape(tok["name"])}</a>')
        for c in tok["children"]:
            toc.append(f'<a class="h3" href="#{c["id"]}">{html.escape(c["name"])}</a>')
    page = (ROOT / "guide.src.html").read_text().replace("{{toc}}", "\n".join(toc)).replace("{{body}}", body)
    (ROOT / "guide.html").write_text(page)


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit("usage: tools/build.py path/to/veya/README.md")
    build_index()
    build_guide(sys.argv[1])
    (ROOT / "code.css").write_text(code_css())
    print("built index.html, guide.html, code.css")
